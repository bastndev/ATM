import * as path from 'path';
import * as vscode from 'vscode';
import { TomlSyntaxError } from '../core/smolToml';
import { validateToml } from '../core/validate';

export const VALIDATION_SETTING = 'atm.toml.validation.enabled';
const DEBOUNCE_MS = 300;
/** Larger documents are not checked while typing. */
const MAX_LENGTH = 2 * 1024 * 1024;

/**
 * Shows TOML syntax errors in the editor and the Problems panel. Error Lens
 * picks them up like any other diagnostic.
 */
export class TomlDiagnostics implements vscode.Disposable {
	private readonly collection = vscode.languages.createDiagnosticCollection('toml');
	private readonly timers = new Map<string, ReturnType<typeof setTimeout>>();
	private readonly disposables: vscode.Disposable[];

	constructor() {
		this.disposables = [
			this.collection,
			vscode.workspace.onDidOpenTextDocument((document) => this.schedule(document, 0)),
			vscode.workspace.onDidChangeTextDocument((event) => this.schedule(event.document, DEBOUNCE_MS)),
			vscode.workspace.onDidCloseTextDocument((document) => this.forget(document.uri)),
			vscode.workspace.onDidChangeConfiguration((event) => {
				if (event.affectsConfiguration(VALIDATION_SETTING)) {
					this.refreshAll();
				}
			}),
		];
		this.refreshAll();
	}

	dispose(): void {
		for (const timer of this.timers.values()) {
			clearTimeout(timer);
		}
		this.timers.clear();
		for (const disposable of this.disposables) {
			disposable.dispose();
		}
	}

	private refreshAll(): void {
		for (const document of vscode.workspace.textDocuments) {
			this.schedule(document, 0);
		}
	}

	private schedule(document: vscode.TextDocument, delay: number): void {
		if (document.languageId !== 'toml') {
			return;
		}
		const key = document.uri.toString();
		const pending = this.timers.get(key);
		if (pending) {
			clearTimeout(pending);
		}
		if (!shouldValidate(document)) {
			this.timers.delete(key);
			this.collection.delete(document.uri);
			return;
		}
		this.timers.set(
			key,
			setTimeout(() => {
				this.timers.delete(key);
				void this.validate(document);
			}, delay),
		);
	}

	private async validate(document: vscode.TextDocument): Promise<void> {
		const version = document.version;
		let problem: TomlSyntaxError | undefined;
		try {
			problem = await validateToml(document.getText());
		} catch (error) {
			console.error('[toml] Validation failed:', error);
			return;
		}
		if (document.isClosed || document.version !== version || !shouldValidate(document)) {
			return; // stale: a newer check is already scheduled
		}
		if (!problem) {
			this.collection.delete(document.uri);
			return;
		}
		const diagnostic = new vscode.Diagnostic(
			problemRange(document, problem),
			problem.message,
			vscode.DiagnosticSeverity.Error,
		);
		diagnostic.source = 'TOML';
		this.collection.set(document.uri, [diagnostic]);
	}

	private forget(uri: vscode.Uri): void {
		const key = uri.toString();
		const pending = this.timers.get(key);
		if (pending) {
			clearTimeout(pending);
			this.timers.delete(key);
		}
		this.collection.delete(uri);
	}
}

function shouldValidate(document: vscode.TextDocument): boolean {
	if (document.languageId !== 'toml') {
		return false;
	}
	if (document.uri.scheme !== 'file' && document.uri.scheme !== 'untitled') {
		return false;
	}
	// Lock files (Cargo.lock, uv.lock) are generated by tools, never hand-edited.
	if (path.extname(document.uri.path) === '.lock') {
		return false;
	}
	if (!vscode.workspace.getConfiguration(undefined, document.uri).get<boolean>(VALIDATION_SETTING, true)) {
		return false;
	}
	return document.getText().length <= MAX_LENGTH;
}

/** Highlights the character smol-toml points at, or the last character when it points past the end of the line. */
function problemRange(document: vscode.TextDocument, problem: TomlSyntaxError): vscode.Range {
	const line = Math.min(Math.max(problem.line - 1, 0), document.lineCount - 1);
	const lineLength = document.lineAt(line).text.length;
	let column = Math.max(problem.column - 1, 0);
	if (column >= lineLength) {
		column = Math.max(lineLength - 1, 0);
	}
	const end = Math.min(column + 1, lineLength);
	return new vscode.Range(line, column, line, end);
}
